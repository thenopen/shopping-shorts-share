// Generates app/fonts.generated.css from public/fonts/*.woff2 (single source of truth).
// Render-identical to the old hand-maintained @font-face wall: family = file basename,
// woff2 format, font-display: swap. Re-run on predev/prebuild (see package.json).
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, "..", "public", "fonts");
const outFile = join(here, "..", "app", "fonts.generated.css");

const families = readdirSync(fontsDir)
  .filter((f) => f.toLowerCase().endsWith(".woff2"))
  .map((f) => f.replace(/\.woff2$/i, ""))
  .sort((a, b) => a.localeCompare(b));

const header =
  "/* AUTO-GENERATED by scripts/gen-font-css.mjs — DO NOT EDIT.\n" +
  "   Source of truth: public/fonts/*.woff2. Regenerated on predev/prebuild. */\n";

const rules = families
  .map(
    (fam) =>
      `@font-face { font-family: "${fam}"; src: url("/fonts/${fam}.woff2") format("woff2"); font-display: swap; }`
  )
  .join("\n");

writeFileSync(outFile, header + rules + "\n");
console.log(`gen-font-css: wrote ${families.length} @font-face -> app/fonts.generated.css`);
